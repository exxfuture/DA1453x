/**
 ****************************************************************************************
 *
 * @file user_aht20.h
 *
 * @brief AHT20 температурен и влажностен I2C сензор — драйвер (заглавен файл).
 *
 * AHT20 е евтин и точен I2C сензор на Aosong:
 *   - I2C адрес: 0x38 (7-bit)
 *   - Диапазон температура: -40°C ... +85°C, точност ±0.3°C
 *   - Диапазон влажност: 0%...100% RH, точност ±2%
 *   - Време за измерване: ~80ms
 *
 * Данните се връщат като цели числа × 10:
 *   temperature_x10 = 253  →  25.3°C
 *   humidity_x10    = 487  →  48.7% RH
 *
 * Типична употреба (в tick_timer_cb, всяка секунда):
 *   1. aht20_trigger_measurement()    — стартира измерване
 *   2. изчакай 80ms (или провери aht20_is_busy())
 *   3. aht20_read(&temp, &hum)        — прочети резултата
 *
 ****************************************************************************************
 */

#ifndef _USER_AHT20_H_
#define _USER_AHT20_H_

/*
 * ВКЛЮЧЕНИ ФАЙЛОВЕ
 ****************************************************************************************
 */
#include <stdint.h>
#include <stdbool.h>

/*
 * ДЕФИНИЦИИ
 ****************************************************************************************
 */

// AHT20 I2C команди (от datasheet-а)
#define AHT20_CMD_INIT              0xBE    // Инициализация (+ 0x08 0x00)
#define AHT20_CMD_TRIGGER           0xAC    // Стартиране на измерване (+ 0x33 0x00)
#define AHT20_CMD_STATUS            0x71    // Четене на статус
#define AHT20_CMD_SOFT_RESET        0xBA    // Софтуерен рестарт

// Битове в статус байта
#define AHT20_STATUS_BUSY_BIT       0x80    // Бит 7: 1 = измерва, 0 = готов
#define AHT20_STATUS_CAL_BIT        0x08    // Бит 3: 1 = калибриран, 0 = некалибриран

/*
 * ДЕКЛАРАЦИИ НА ФУНКЦИИ
 ****************************************************************************************
 */

/**
 ****************************************************************************************
 * @brief Инициализация на AHT20 сензора.
 *
 * Проверява дали сензорът е калибриран (бит 3 на статуса).
 * Ако не е — изпраща команда за инициализация (0xBE 0x08 0x00).
 *
 * ВАЖНО: Извикай СЛЕД i2c_init() и след 40ms от включване на захранването!
 *
 * @return true  — сензорът е готов (калибриран)
 * @return false — комуникацията се провали или сензорът не се калибрира
 ****************************************************************************************
 */
bool aht20_init(void);

/**
 ****************************************************************************************
 * @brief Стартира измерване на температура и влажност.
 *
 * Изпраща команда 0xAC 0x33 0x00 по I2C.
 * След това трябва да изчакаш ~80ms преди да четеш резултата!
 ****************************************************************************************
 */
void aht20_trigger_measurement(void);

/**
 ****************************************************************************************
 * @brief Проверява дали сензорът все още измерва.
 *
 * Чете статус байта и проверява бит 7 (BUSY).
 *
 * @return true  — сензорът е зает (все още измерва)
 * @return false — измерването е готово, може да четеш
 ****************************************************************************************
 */
bool aht20_is_busy(void);

/**
 ****************************************************************************************
 * @brief Прочита температурата и влажността от сензора.
 *
 * Чете 6 байта (status + 5 байта данни) от I2C.
 * Извлича 2 × 20-bit стойности и ги преобразува:
 *   - temp_x10: температура × 10 (пример: 253 = 25.3°C)
 *   - hum_x10:  влажност × 10 (пример: 487 = 48.7%)
 *
 * ВАЖНО: Извикай СЛЕД aht20_trigger_measurement() + 80ms изчакване!
 *
 * @param[out] temp_x10  указател към int16_t за температурата (× 10)
 * @param[out] hum_x10   указател към uint16_t за влажността (× 10)
 *
 * @return true  — данните са прочетени успешно
 * @return false — грешка при четене или сензорът е зает
 ****************************************************************************************
 */
bool aht20_read(int16_t *temp_x10, uint16_t *hum_x10);

/**
 ****************************************************************************************
 * @brief Сканира I2C шината за активни устройства (адреси 0x08..0x77).
 *
 * За всеки адрес опитва 1-байтов write. Ако няма ABORT → устройство открито.
 * Отпечатва резултатите чрез UART (arch_printf).
 * Накрая възстановява AHT20 адреса (0x38).
 ****************************************************************************************
 */
void i2c_scan_bus(void);

#endif // _USER_AHT20_H_

